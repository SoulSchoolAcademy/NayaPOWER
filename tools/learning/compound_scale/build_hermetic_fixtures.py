"""Build hermetic citation fixtures for every compound_scale registry lesson.

Reads tools/learning/compound_scale/lessons_registry.json, writes one fixture
per lesson at tools/learning/compound_scale/receipts/<id>.md containing the
registered receipt_quote verbatim (plus the contradicting_quote on its own
line for must_contradict lessons), and repoints every lesson's
receipt_file at the repo-relative fixture path.

Rationale: the registry's citations pinned quotes against mutable,
out-of-repo VM-home files (~/MEMORY.md, ~/TOOLS.md, ...). When those files
drifted, gate_truth returned 4 ("quote not in it") instead of 9 — a silent
red on developer VMs that CI never saw (the hermetic fallback keys on file
absence, not drift). Committed fixtures make citation integrity
byte-identical everywhere.
"""
import json
from pathlib import Path

PKG = Path(__file__).resolve().parent
REGISTRY = PKG / "lessons_registry.json"
FIXDIR = PKG / "receipts"

HEADER = ("# Hermetic citation fixture — do not edit by hand.\n"
          "# Generated by tools/learning/compound_scale/build_hermetic_fixtures.py\n"
          "# from lessons_registry.json. Contains the registered citation bytes\n"
          "# verbatim so gate_truth is byte-identical on every machine.\n\n")


def main() -> None:
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    FIXDIR.mkdir(exist_ok=True)
    for lesson in reg["lessons"]:
        lid = lesson["id"]
        truth = lesson["truth"]
        quote = truth["receipt_quote"]
        contra = truth.get("contradicting_quote", "")
        body = HEADER + quote + "\n"
        if contra and contra not in quote:
            body += contra + "\n"
        (FIXDIR / f"{lid}.md").write_text(body, encoding="utf-8")
        truth["receipt_file"] = f"tools/learning/compound_scale/receipts/{lid}.md"
    REGISTRY.write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(f"wrote {len(reg['lessons'])} fixtures; registry repointed")


if __name__ == "__main__":
    main()
